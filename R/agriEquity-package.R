#' agriEquity: Equity and Sustainability Assessment of Agricultural
#' Subsidies
#'
#' An integrated framework for distributional analysis of agricultural
#' support, budget-neutral subsidy allocation and
#' productivity-equity-sustainability trade-offs.
#'
#' * [benefit_incidence()] - who receives the subsidy, by group or
#'   quantile.
#' * [progressivity_index()] - concentration, Kakwani and
#'   Reynolds-Smolensky measures.
#' * [subsidy_equity()] - multi-dimensional equity scorecard with Theil
#'   decomposition.
#' * [distributional_effects()] - inequality and poverty with and without
#'   the subsidy, for one or more scenarios.
#' * [budget_reallocation()] - budget-neutral allocation rules, including a
#'   welfare-optimal allocation.
#' * [tradeoff_frontier()] - productivity-equity-sustainability frontier.
#'
#' The example data set [farm_subsidy] is simulated.
#'
#' @keywords internal
